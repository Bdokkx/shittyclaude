		if container[c] then
			local d = dst:FindFirstChild(c.Name)
			if d and not d:IsA("Folder") then
				table.insert(skipped, d:GetFullName())
			else
				if not d then
					d = Instance.new("Folder")
					d.Name = c.Name
					d.Parent = dst
				end
				place(c, d)
			end
		else
			for _, old in ipairs(dst:GetChildren()) do
				if old.Name == c.Name then
					old:Destroy()
					replaced = replaced + 1
				end
			end
			c.Parent = dst
			placed = placed + 1
		end
	end
end
place(root, live)
root:Destroy()
for _, s in ipairs(skipped) do
	warn(TAG .. s .. " is not a Folder, so nothing was put in it.")
end

pcall(function() ChangeHistoryService:SetWaypoint("Built the Frost Fields potatoes") end)
print(TAG .. string.format("built the Frost Fields potatoes in ReplicatedStorage.%s: %d items (%d replaced), %d parts", KIT_NAME,
	placed, replaced, parts))
