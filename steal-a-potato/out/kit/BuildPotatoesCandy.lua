local function setSurfaces(p, kind)
	local s = kind == 3 and Enum.SurfaceType.Inlet or Enum.SurfaceType.Smooth
	p.TopSurface, p.BottomSurface = s, s
	p.FrontSurface, p.BackSurface, p.LeftSurface, p.RightSurface = s, s, s, s
end
