		local p
		if shape == "W" then
			p = Instance.new("WedgePart")
		else
			p = Instance.new("Part")
			p.Shape = (shape == "C" and Enum.PartType.Cylinder) or (shape == "S" and Enum.PartType.Ball)
				or Enum.PartType.Block
		end
		p.Name = nm(f[3])
		p.Size = Vector3.new(tonumber(f[5]), tonumber(f[6]), tonumber(f[7]))
