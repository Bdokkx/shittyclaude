	elseif k == "G" or k == "N" then
		local a = Instance.new(k == "G" and "AnimationController" or "Animator")
		a.Name = nm(f[3])
		add(a, f)
	elseif k == "S" then
		local ks = Instance.new("KeyframeSequence")
		ks.Name = nm(f[3])
		ks.Loop = f[4] == "1"
		ks.Priority = PRIORITY[tonumber(f[5])] or Enum.AnimationPriority.Action
