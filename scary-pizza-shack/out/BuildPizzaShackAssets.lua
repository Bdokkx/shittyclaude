		inst[n] = p
		meshOf[p] = mi
		counts.meshes = counts.meshes + 1
	elseif k == "A" then
		local par = inst[tonumber(f[2])]
		local a = Instance.new("Attachment")
		a.Name = nm(f[3])
		a.CFrame = par.CFrame:Inverse() * cfAt(f, 4)
		a.Parent = par
		n = n + 1
		inst[n] = a
