		p.Parent = inst[tonumber(f[2])]
		n = n + 1
		inst[n] = p
		counts.parts = counts.parts + 1
	elseif k == "K" then
		local p = Instance.new("Part")
		p.Name = nm(f[3])
		p.Size = Vector3.new(1, 1, 1)
		p.CFrame = cfAt(f, 4)
