local ChangeHistoryService = game:GetService("ChangeHistoryService")
local ServerStorage = game:GetService("ServerStorage")
local TAG = "FolkValley Grim Reaper: "

-- 1. find the imported meshes (the importer puts them in Workspace)
local meshes, loose = {}, {}
local function norm(s)
	return (string.lower(s):gsub("[^%w]", ""))
end
for _, root in ipairs({workspace, ServerStorage, game:GetService("ReplicatedStorage")}) do
	for _, d in ipairs(root:GetDescendants()) do
		if d:IsA("MeshPart") then
			if meshes[d.Name] == nil then
				meshes[d.Name] = d
			end
			if loose[norm(d.Name)] == nil then
				loose[norm(d.Name)] = d
			end
		end
	end
end
local function mesh(name)
	return meshes[name] or loose[norm(name)]
end
local missing = {}
for _, name in ipairs({"FV_AxisO", "FV_AxisX", "FV_AxisY", "FV_AxisZ"}) do
	if mesh(name) == nil then
		table.insert(missing, name)
	end
end
for _, p in ipairs(PARTS) do
	if mesh(p.Mesh) == nil then
		table.insert(missing, p.Mesh)
	end
end
if #missing > 0 then
	warn(TAG .. #missing .. " imported meshes not found (first: " .. missing[1]
		.. "). Import FolkValley_GrimReaper.fbx with File > Import 3D first, with Merge Meshes off.")
	return
end

-- 2. work out how the importer scaled / turned the file from the marker cubes
local o = mesh("FV_AxisO").Position
local ex = mesh("FV_AxisX").Position - o
local ey = mesh("FV_AxisY").Position - o
local ez = mesh("FV_AxisZ").Position - o
local scale = (ex.Magnitude + ey.Magnitude + ez.Magnitude) / (3 * MARKER_STEP)
if ex.Unit:Cross(ey.Unit):Dot(ez.Unit) < 0.9 then
	warn(TAG .. "the import looks mirrored. Re-import with the default axis settings.")
	return
end
local fromFile = CFrame.fromMatrix(Vector3.zero, ex.Unit, ey.Unit, ez.Unit):Inverse()

ChangeHistoryService:SetWaypoint("Before building the Grim Reaper")

-- 3. the model, built standing at BUILD_AT (model space = Roblox space, facing -Z)
local BUILD_AT = CFrame.new(0, 2000, 0)
local model = Instance.new("Model")
model.Name = MODEL_NAME
local function flags(part, collide)
	part.Anchored = false
	part.CanCollide = collide
	part.CanTouch = true
	part.CanQuery = true
	part.Massless = not collide
end
local hrp = Instance.new("Part")
hrp.Name = "HumanoidRootPart"
hrp.Size = HRP.Size
hrp.CFrame = BUILD_AT * CFrame.new(HRP.Center)
hrp.Transparency = 1
hrp.TopSurface = Enum.SurfaceType.Smooth
hrp.BottomSurface = Enum.SurfaceType.Smooth
flags(hrp, true)
hrp.Parent = model
local bones = {HumanoidRootPart = hrp}
local containers = {}
for _, p in ipairs(PARTS) do
	local part = mesh(p.Mesh)
	containers[part.Parent] = true
	local turn = fromFile * (part.CFrame - part.CFrame.Position)
	for _, child in ipairs(part:GetChildren()) do
		child:Destroy() -- importer extras (SurfaceAppearance, attachments)
	end
	part.Name = p.Name
	part.Size = part.Size / scale
	part.CFrame = BUILD_AT * CFrame.new(p.Center) * turn
	part.Color = p.Color
	part.Material = p.Material
	part.Transparency = p.Transparency
	part.Reflectance = 0
	part.CastShadow = true
	pcall(function() part.TextureID = "" end)
	pcall(function() part.CollisionFidelity = Enum.CollisionFidelity.Box end)
	flags(part, false)
	part.Parent = model
	if p.Name == p.Bone then
		bones[p.Bone] = part
	end
end
for _, p in ipairs(PARTS) do -- the rest of each bone is welded to its main part
	if p.Name ~= p.Bone then
		local part = model:FindFirstChild(p.Name)
		local weld = Instance.new("WeldConstraint")
		weld.Part0 = bones[p.Bone]
		weld.Part1 = part
		weld.Parent = part
	end
end
for _, j in ipairs(RIG) do
	local p0, p1 = bones[j.Part0], bones[j.Part1]
	local pivot = BUILD_AT * CFrame.new(j.Pivot)
	local motor = Instance.new("Motor6D")
	motor.Name = j.Motor
	motor.Part0 = p0
	motor.Part1 = p1
	motor.C0 = p0.CFrame:Inverse() * pivot
	motor.C1 = p1.CFrame:Inverse() * pivot
	motor.Parent = p1
end

local humanoid = Instance.new("Humanoid")
humanoid.RigType = Enum.HumanoidRigType.R15
humanoid.AutomaticScalingEnabled = false
humanoid.HipHeight = HIP_HEIGHT
humanoid.BreakJointsOnDeath = false
humanoid.RequiresNeck = false
humanoid.MaxHealth = DEFAULT_ATTRIBUTES.MaxHealth
humanoid.Health = DEFAULT_ATTRIBUTES.MaxHealth
humanoid.WalkSpeed = DEFAULT_ATTRIBUTES.WalkSpeed
pcall(function() humanoid.UseJumpPower = true end)
humanoid.JumpPower = 0
humanoid.DisplayDistanceType = Enum.HumanoidDisplayDistanceType.None
humanoid.HealthDisplayType = Enum.HumanoidHealthDisplayType.AlwaysOff
humanoid.Parent = model
Instance.new("Animator").Parent = humanoid

local attach = {}
for _, a in ipairs(ATTACH) do
	local at = Instance.new("Attachment")
	at.Name = a.Name
	at.CFrame = bones[a.Bone].CFrame:Inverse() * (BUILD_AT * CFrame.new(a.Position))
	at.Parent = bones[a.Bone]
	attach[a.Name] = at
end

-- effects: all built-in, nothing to upload
pcall(function()
	local light = Instance.new("PointLight")
	light.Color = GLOW
	light.Brightness = 3
	light.Range = 16
	light.Shadows = false
	light.Parent = attach.EyeGlow
end)
pcall(function()
	local area = Instance.new("Part")
	area.Name = "MistArea"
	area.Size = Vector3.new(9, 0.4, 7.5)
	area.CFrame = BUILD_AT * CFrame.new(0, 0.5, 0)
	area.Transparency = 1
	area.Anchored = false
	area.CanCollide = false
	area.CanTouch = false
	area.CanQuery = false
	area.Massless = true
	area.Parent = model
	local weld = Instance.new("WeldConstraint")
	weld.Part0 = bones.LowerTorso
	weld.Part1 = area
	weld.Parent = area
	local mist = Instance.new("ParticleEmitter")
	mist.Name = "Mist"
	mist.Texture = "rbxasset://textures/particles/smoke_main.dds"
	mist.Color = ColorSequence.new(MIST, Color3.fromRGB(20, 12, 34))
	mist.Size = NumberSequence.new({NumberSequenceKeypoint.new(0, 2.5), NumberSequenceKeypoint.new(1, 6)})
	mist.Transparency = NumberSequence.new({NumberSequenceKeypoint.new(0, 1), NumberSequenceKeypoint.new(0.25, 0.55),
		NumberSequenceKeypoint.new(1, 1)})
	mist.Lifetime = NumberRange.new(2, 3.2)
	mist.Rate = 12
	mist.Speed = NumberRange.new(0.4, 1.4)
	mist.SpreadAngle = Vector2.new(180, 180)
	mist.Acceleration = Vector3.new(0, 0.5, 0)
	mist.RotSpeed = NumberRange.new(-25, 25)
	mist.Rotation = NumberRange.new(0, 360)
	mist.LightEmission = 0.15
	mist.Shape = Enum.ParticleEmitterShape.Box
	mist.ShapeStyle = Enum.ParticleEmitterShapeStyle.Volume
	mist.Parent = area
end)
pcall(function()
	local trail = Instance.new("Trail")
	trail.Name = "ScytheTrail"
	trail.Attachment0 = attach.BladeBase
	trail.Attachment1 = attach.BladeTip
	trail.Color = ColorSequence.new(GLOW, Color3.fromRGB(150, 70, 230))
	trail.Transparency = NumberSequence.new({NumberSequenceKeypoint.new(0, 0.15), NumberSequenceKeypoint.new(1, 1)})
	trail.Lifetime = 0.35
	trail.LightEmission = 1
	trail.FaceCamera = false
	trail.Enabled = false
	trail.Parent = bones.Scythe
end)

local controller = Instance.new("Script")
controller.Name = "ReaperController"
local okSource = pcall(function() controller.Source = CONTROLLER_SOURCE end)
controller.Parent = model
if not okSource then
	warn(TAG .. "couldn't write the controller script; paste ReaperController.lua into it by hand")
end
for k, v in pairs(DEFAULT_ATTRIBUTES) do
	model:SetAttribute(k, v)
end
model.PrimaryPart = hrp

-- 4. stand it on the ground where the camera is looking, facing the camera
local spot = CFrame.new(0, 0, 0)
pcall(function()
	local cam = workspace.CurrentCamera
	local focus = cam.Focus.Position
	local params = RaycastParams.new()
	params.FilterDescendantsInstances = {model}
	local hit = workspace:Raycast(focus + Vector3.new(0, 60, 0), Vector3.new(0, -400, 0), params)
	local ground = hit and hit.Position or focus
	local look = (cam.CFrame.Position - ground) * Vector3.new(1, 0, 1)
	if look.Magnitude < 1e-3 then
		look = Vector3.new(0, 0, 1)
	end
	-- the model faces -Z: point that at the camera
	spot = CFrame.lookAt(ground, ground + look.Unit)
end)
model.Parent = workspace
model:PivotTo(spot * CFrame.new(HRP.Center))

-- 5. tidy up: every marker cube (from every import of the file) and the now-empty imported model
for _, root in ipairs({workspace, ServerStorage, game:GetService("ReplicatedStorage")}) do
	for _, d in ipairs(root:GetDescendants()) do
		if d:IsA("BasePart") and d.Name:match("^FV_Axis[OXYZ]$") then
			containers[d.Parent] = true
			d:Destroy()
		end
	end
end
for container in pairs(containers) do
	local c = container
	while c and c ~= game and c ~= workspace and c.Parent and not c:IsA("Folder") do
		local hasParts = false
		for _, d in ipairs(c:GetDescendants()) do
			if d:IsA("BasePart") then
				hasParts = true
				break
			end
		end
		if hasParts then
			break
		end
		local parent = c.Parent
		c:Destroy()
		c = parent
	end
end

ChangeHistoryService:SetWaypoint("Built the Grim Reaper")
game:GetService("Selection"):Set({model})
print(TAG .. "built Workspace." .. model.Name .. " (" .. #PARTS .. " mesh parts). Drag GrimReaper_Animations.rbxm into "
	.. "ServerStorage for its animations; see the README for publishing them.")
